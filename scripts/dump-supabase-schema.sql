-- Supabase の public スキーマ + Storage の構成を、再作成用 SQL として 1 行 1 文で出力する。
-- データ (行) は一切出力しない。読み取り専用で、実行しても何も作成・変更しない。
-- ※ テーブル作成文の文字列を 2 つに分割しているのは、Supabase SQL Editor が
--   文字列を本物の作成文と誤検知して RLS 警告を出すのを避けるため。
with tbl as (
  select c.oid, c.relname
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
),
cols as (
  select a.attrelid,
         string_agg(
           format('  %I %s%s%s%s',
             a.attname,
             format_type(a.atttypid, a.atttypmod),
             case a.attidentity when 'a' then ' generated always as identity'
                                when 'd' then ' generated by default as identity' else '' end,
             case when a.attnotnull and a.attidentity = '' then ' not null' else '' end,
             coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), '')),
           E',\n' order by a.attnum) as body
  from pg_attribute a
  join tbl on tbl.oid = a.attrelid
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where a.attnum > 0 and not a.attisdropped
  group by a.attrelid
),
cons as (
  select conrelid,
         string_agg(format('  constraint %I %s', conname, pg_get_constraintdef(oid)),
                    E',\n' order by contype, conname) as body
  from pg_constraint
  where conrelid in (select oid from tbl) and contype in ('p', 'u', 'c')
  group by conrelid
),
seqs as (
  -- serial 列などのシーケンス (identity 列が内部で持つものは除く)
  select s.oid, d.refobjid as tbl_oid, a.attname
  from pg_class s
  join pg_namespace n on n.oid = s.relnamespace
  left join pg_depend d on d.objid = s.oid and d.classid = 'pg_class'::regclass and d.deptype in ('a', 'i')
  left join pg_attribute a on a.attrelid = d.refobjid and a.attnum = d.refobjsubid
  where n.nspname = 'public' and s.relkind = 'S' and coalesce(d.deptype, 'a') <> 'i'
),
stmts as (
  -- 0. シーケンス (テーブルの default より先に必要)
  select 0 as section, s.oid::regclass::text as name,
         format('create sequence if not exists %s;', s.oid::regclass) as sql
  from seqs s
  union all
  -- 1. テーブル (外部キーは後で追加するので順序に依存しない)
  select 1, t.relname,
         format(E'create ' || E'table public.%I (\n%s%s\n);', t.relname, cols.body,
                coalesce(E',\n' || cons.body, '')) as sql
  from tbl t join cols on cols.attrelid = t.oid left join cons on cons.conrelid = t.oid
  union all
  -- 2. 外部キー
  select 2, conrelid::regclass::text || conname,
         format('alter table public.%I add constraint %I %s;', conrelid::regclass::text, conname, pg_get_constraintdef(oid))
  from pg_constraint
  where conrelid in (select oid from tbl) and contype = 'f'
  union all
  -- 2. シーケンスの所有者 (テーブル削除時に一緒に消えるように)
  select 2, s.oid::regclass::text,
         format('alter sequence %s owned by %s.%I;', s.oid::regclass, s.tbl_oid::regclass, s.attname)
  from seqs s
  where s.tbl_oid is not null
  union all
  -- 3. インデックス (主キー / unique 制約が作るものは除く)
  select 3, i.tablename || i.indexname, i.indexdef || ';'
  from pg_indexes i
  where i.schemaname = 'public'
    and not exists (select 1 from pg_constraint c where c.conname = i.indexname and c.contype in ('p', 'u'))
  union all
  -- 4. ビュー
  select 4, c.relname, format(E'create view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid))
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
  union all
  -- 5. 関数 (拡張機能が入れたものは除く)
  select 5, p.proname, pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  -- 6. トリガー
  select 6, t.tgname, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t
  where t.tgrelid in (select oid from tbl) and not t.tgisinternal
  union all
  -- 7. RLS 有効化
  select 7, c.relname, format('alter table public.%I enable row level security;', c.relname)
  from pg_class c join tbl on tbl.oid = c.oid
  where c.relrowsecurity
  union all
  -- 8. RLS ポリシー (public + storage)
  select 8, p.schemaname || p.tablename || p.policyname,
         format('create policy %I on %I.%I as %s for %s to %s%s%s;',
           p.policyname, p.schemaname, p.tablename, lower(p.permissive), lower(p.cmd),
           array_to_string(p.roles, ', '),
           coalesce(' using (' || p.qual || ')', ''),
           coalesce(' with check (' || p.with_check || ')', ''))
  from pg_policies p
  where p.schemaname in ('public', 'storage')
  union all
  -- 9. Storage バケット
  select 9, b.id,
         format('insert into storage.buckets (id, name, public) values (%L, %L, %s);', b.id, b.name, b.public::text)
  from storage.buckets b
)
select sql from stmts order by section, name;
